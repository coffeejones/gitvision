#!/usr/bin/env python3
"""GROUND TRUTH for entry-point detection: ask the framework.

Flask and Django both know exactly which routes they serve and which function
each dispatches to. That makes this the rarest kind of oracle — exact, free,
and generated by the system under test rather than by a third party.

  python3 bench/entrypointOracle.py flask   <repo> <import-expr>
  python3 bench/entrypointOracle.py django  <repo> <settings-module>

Emits JSON: [{"file": "<repo-rel>", "function": "...", "route": "...", "methods": [...]}]
"""
import inspect, json, os, sys


def emit(rows, repo):
    out = []
    for r in rows:
        f = r.get("file")
        if f:
            try:
                f = os.path.relpath(os.path.realpath(f), os.path.realpath(repo))
            except ValueError:
                pass
        # Framework code is not the user's repo even when a venv happens to sit
        # inside it. Django's own admin views are genuinely served, but they are
        # not something the analysed repo declares or can fix.
        if f and not f.startswith("..") and not any(
            seg in f.split(os.sep)
            for seg in ("site-packages", "dist-packages", ".venv", "venv", ".tox")
        ):
            r["file"] = f
            out.append(r)
    json.dump(out, sys.stdout, indent=1)


def flask_routes(repo, expr):
    sys.path.insert(0, repo)
    for extra in ("src", "app", "backend"):
        p = os.path.join(repo, extra)
        if os.path.isdir(p):
            sys.path.insert(0, p)
    app = eval(expr, {"__builtins__": __builtins__})  # e.g. "create_app()" after import
    rows = []
    for rule in app.url_map.iter_rules():
        view = app.view_functions.get(rule.endpoint)
        if view is None:
            continue
        # UNWRAP FIRST. A view wrapped in @login_required reports the
        # decorator's file, not its own — which made this oracle blame the
        # engine for three handlers it had located correctly.
        fn = inspect.unwrap(getattr(view, "view_class", view))
        try:
            file = inspect.getsourcefile(fn)
        except TypeError:
            file = None
        rows.append({
            "file": file,
            "function": getattr(fn, "__name__", str(fn)),
            "route": str(rule.rule),
            "methods": sorted(m for m in (rule.methods or []) if m not in ("HEAD", "OPTIONS")),
        })
    return rows


def django_routes(repo, settings_mod):
    sys.path.insert(0, repo)
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", settings_mod)
    import django
    django.setup()
    from django.urls import get_resolver
    rows = []

    def walk(patterns, prefix=""):
        for p in patterns:
            if hasattr(p, "url_patterns"):          # an include()
                walk(p.url_patterns, prefix + str(p.pattern))
                continue
            cb = getattr(p, "callback", None)
            if cb is None:
                continue
            fn = getattr(cb, "view_class", cb)      # as_view() wrappers
            fn = inspect.unwrap(fn)
            try:
                file = inspect.getsourcefile(fn)
            except TypeError:
                file = None
            rows.append({
                "file": file,
                "function": getattr(fn, "__name__", str(fn)),
                "route": prefix + str(p.pattern),
                "methods": sorted(getattr(fn, "http_method_names", []) or []),
            })

    walk(get_resolver().url_patterns)
    return rows


if __name__ == "__main__":
    kind, repo, arg = sys.argv[1], os.path.abspath(sys.argv[2]), sys.argv[3]
    emit(flask_routes(repo, arg) if kind == "flask" else django_routes(repo, arg), repo)
